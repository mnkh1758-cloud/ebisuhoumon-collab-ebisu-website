#!/bin/bash
# えびすHP08 GitHubアップロード用スクリプト

echo "========================================="
echo "  えびすHP08 - GitHubアップロードスクリプト"
echo "========================================="

# 1. すべての変更をステージングに追加
echo "変更されたファイルを準備しています..."
git add .

# 2. 変更をコミット
echo "変更をコミットしています..."
git commit -m "Update: えびすHP08 最新の画像URL修正（WebP対応）とレイアウト更新を反映"

# 3. GitHubへプッシュ（メインブランチへ）
# ※ 初回の場合は事前に 'git remote add origin <あなたのGitHubリポジトリURL>' が必要です。
echo "GitHubへデータをアップロードしています..."
git push origin main

echo "========================================="
echo "  アップロードが完了しました！"
echo "========================================="
